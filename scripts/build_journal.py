def json_ld_index(entries: list[dict]) -> str:
    items = []
    for idx, entry in enumerate([e for e in entries if e.get("status") == "published" and e.get("page")], 1):
        items.append({"@type": "ListItem", "position": idx, "url": entry["canonical_url"], "name": entry["title"]})
    data = {"@context": "https://schema.org", "@type": "CollectionPage", "name": "SDPP Palm Journal", "url": f"{BASE_URL}/palm-journal-new.html", "mainEntity": {"@type": "ItemList", "itemListElement": items}}
    return f'  <script type="application/ld+json">\n{json.dumps(data, indent=2)}\n  </script>'


def json_ld_article(entry: dict) -> str:
    data = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": entry["title"],
        "description": meta_description(entry),
        "image": absolutize(entry["primary_image"]),
        "datePublished": entry["date"],
        "dateModified": entry.get("modified_date", MODIFIED_DATE),
        "author": {"@type": "Organization", "name": "San Diego Palm Protection"},
        "publisher": {"@type": "Organization", "name": "San Diego Palm Protection", "logo": {"@type": "ImageObject", "url": f"{BASE_URL}/logo.png"}},
        "mainEntityOfPage": entry["canonical_url"],
    }
    return f'  <script type="application/ld+json">\n{json.dumps(data, indent=2)}\n  </script>'


