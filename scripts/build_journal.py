def read_entries() -> list[dict]:
    entries = json.loads(MANIFEST.read_text(encoding="utf-8"))
    seen_slugs = set()
    seen_anchors = set()
    errors = []
    for entry in entries:
        required = [
            "slug", "title", "date", "date_label", "location", "category", "excerpt",
            "primary_image", "primary_image_alt", "legacy_anchor", "status", "page",
        ]
        for key in required:
            if key not in entry or entry[key] in ("", None):
                errors.append(f"{entry.get('slug', '<unknown>')}: missing {key}")
        slug = entry.get("slug", "")
        anchor = entry.get("legacy_anchor", "")
        if slug in seen_slugs:
            errors.append(f"duplicate slug: {slug}")
        if anchor in seen_anchors:
            errors.append(f"duplicate legacy anchor: {anchor}")
        seen_slugs.add(slug)
        seen_anchors.add(anchor)
        if entry.get("status") == "draft":
            continue
        image_path = normalize_site_path(entry.get("primary_image", ""))
        if image_path and not (ROOT / image_path).exists():
            errors.append(f"{slug}: missing primary image {entry.get('primary_image')}")
        if entry.get("page"):
            content_path = CONTENT_DIR / f"{slug}.html"
            if not content_path.exists():
                errors.append(f"{slug}: missing article content snippet {content_path}")
    if errors:
        raise SystemExit("\n".join(errors))
    return entries


def normalize_site_path(path: str) -> str:
    return path.replace("../", "").replace("./", "").split("#", 1)[0]


def absolutize(path: str) -> str:
    clean = normalize_site_path(path)
    return f"{BASE_URL}/{clean}" if clean else BASE_URL


def article_href(entry: dict, from_root: bool = True) -> str:
    prefix = "./" if from_root else ""
    return f"{prefix}palm-journal/{entry['slug']}.html" if from_root else f"./{entry['slug']}.html"


def card_image_src(entry: dict) -> str:
    return entry.get("primary_image", "./journal-hero.jpg")



def display_meta(entry: dict) -> str:
    date_label = entry.get("date_label", "")
    location = entry.get("location", "")
    if location and location.lower() not in date_label.lower():
        return f"{date_label} | {location}"
    return date_label

def page_title(entry: dict) -> str:
    return f"{entry['title']} | SDPP Palm Journal"


def meta_description(entry: dict) -> str:
    text = entry.get("excerpt", "")
    if len(text) > 155:
        text = text[:152].rstrip() + "..."
    return text


def shared_head(title: str, description: str, canonical: str, og_image: str, extra_json_ld: str = "") -> str:
    return f'''  <meta charset="UTF-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n  <title>{escape(title)}</title>\n  <meta name="description" content="{escape(description)}">\n  <link rel="canonical" href="{escape(canonical)}">\n  <meta property="og:title" content="{escape(title)}">\n  <meta property="og:description" content="{escape(description)}">\n  <meta property="og:image" content="{escape(og_image)}">\n  <meta property="og:type" content="article">\n{extra_json_ld}'''


