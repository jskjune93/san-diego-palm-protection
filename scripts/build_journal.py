def json_ld_index(entries: list[dict]) -> str:
    items = []
    for idx, entry in enumerate([e for e in entries if e.get("status") == "published" and e.get("page")], 1):
        items.append({"@type": "ListItem", "position": idx, "url": entry["canonical_url"], "name": entry["title"]})
    data = {"@context": "https://schema.org", "@type": "CollectionPage", "name": "SDPP Palm Journal", "url": f"{BASE_URL}/palm-journal-new.html", "mainEntity": {"@type": "ItemList", "itemListElement": items}}
    return f'  <script type="application/ld+json">\n{json.dumps(data, indent=2)}\n  </script>'


