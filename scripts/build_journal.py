def update_sitemap(entries: list[dict]) -> None:
    existing = SITEMAP_PATH.read_text(encoding="utf-8")
    ns_match = re.search(r'<urlset[^>]*xmlns="([^"]+)"', existing)
    ns = ns_match.group(1) if ns_match else "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace('', ns)
    tree = ET.parse(SITEMAP_PATH)
    root_el = tree.getroot()
    loc_tag = f"{{{ns}}}loc"
    url_tag = f"{{{ns}}}url"
    lastmod_tag = f"{{{ns}}}lastmod"
    changefreq_tag = f"{{{ns}}}changefreq"
    priority_tag = f"{{{ns}}}priority"

    urls_by_loc = {}
    for url in root_el.findall(f".//{url_tag}"):
        loc_node = url.find(loc_tag)
        if loc_node is not None and loc_node.text:
            urls_by_loc[loc_node.text] = url

    documented_loss_url = urls_by_loc.get(DOCUMENTED_LOSS_URL)
    if documented_loss_url is None:
        documented_loss_url = ET.SubElement(root_el, url_tag)
        ET.SubElement(documented_loss_url, loc_tag).text = DOCUMENTED_LOSS_URL
    for tag, value in (
        (lastmod_tag, DOCUMENTED_LOSS_LASTMOD),
        (changefreq_tag, "monthly"),
        (priority_tag, "0.75"),
    ):
        node = documented_loss_url.find(tag)
        if node is None:
            node = ET.SubElement(documented_loss_url, tag)
        node.text = value

    existing_locs = set(urls_by_loc)
    existing_locs.add(DOCUMENTED_LOSS_URL)
    core_manifest = ROOT / "site-config" / "core_routes.json"
    if core_manifest.exists():
        for filename in json.loads(core_manifest.read_text(encoding="utf-8")):
            loc = f"{BASE_URL}/" if filename == "index.html" else f"{BASE_URL}/{filename}"
            if loc in existing_locs:
                continue
            url = ET.SubElement(root_el, url_tag)
            ET.SubElement(url, loc_tag).text = loc
            ET.SubElement(url, lastmod_tag).text = MODIFIED_DATE
            ET.SubElement(url, changefreq_tag).text = "monthly"
            ET.SubElement(url, priority_tag).text = "0.80"
            existing_locs.add(loc)
    for entry in entries:
        if not (entry.get("status") == "published" and entry.get("page")):
            continue
        loc = entry["canonical_url"]
        if loc in existing_locs:
            continue
        url = ET.SubElement(root_el, url_tag)
        ET.SubElement(url, loc_tag).text = loc
        ET.SubElement(url, lastmod_tag).text = entry.get("modified_date", MODIFIED_DATE)
        ET.SubElement(url, changefreq_tag).text = "monthly"
        ET.SubElement(url, priority_tag).text = "0.70"
    tree.write(SITEMAP_PATH, encoding="utf-8", xml_declaration=True)


def main() -> None:
    entries = read_entries()
    JOURNAL_DIR.mkdir(exist_ok=True)
    for old_page in JOURNAL_DIR.glob("*.html"):
        old_page.unlink()
    entries_by_slug = {entry["slug"]: entry for entry in entries}
    render_index(entries)
    for entry in entries:
        if entry.get("status") == "published" and entry.get("page"):
            render_article(entry, entries_by_slug)
    render_documented_loss_page()
    update_sitemap(entries)
    print(f"Generated Palm Journal library and {sum(1 for e in entries if e.get('page') and e.get('status') == 'published')} article pages.")


if __name__ == "__main__":
    main()
